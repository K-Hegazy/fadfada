import { GoogleGenAI } from '@google/genai';

const apiKey = process.env.GEMINI_API_KEY || '';
let genAI: GoogleGenAI | null = null;
if (apiKey) {
  try {
    genAI = new GoogleGenAI({ apiKey });
  } catch (e) {
    console.error('Failed to initialize GoogleGenAI:', e);
  }
}

const SYSTEM_PROMPT = `أنت "مساعد فضفضه" — المساعد الإرشادي الذكي والودود لمنصة "فضفضه" (Fadfada) الاجتماعية العربية.
مهمتك الحصرية هي مساعدة المستخدمين والإجابة عن استفساراتهم حول كيفية استخدام المنصة وقوانينها بأسلوب عربي راقٍ، مهذب وواضح.

قواعد المنصة التي تشرحها للمستخدمين:
1. "المتصلون الآن": الدليل الحي للمستخدمين المتواجدين حالياً، يتم ترتيبهم حسب بلدك أولاً (إناث ثم ذكور) ثم باقي الدول (إناث ثم ذكور). الإناث يبرزن بألوان زهرية أنيقة والذكور بألوان سماوية.
2. "الغرف والمجالس": أقسام حوارية منفصلة تماماً ينشئها المالك/الإدارة للنقاش الجماعي في مواضيع متنوعة (فضفضة، شعر وأدب، تقنية، ألعاب).
3. "الرسائل الخاصة": محادثات مشفرة تدعم الرسائل النصية، الصور ذاتية التدمير (تختفي بعد المشاهدة أو ثوانٍ معدودة)، الرسائل الصوتية المسجلة، وإرسال الهدايا والتفاعلات.
4. "نظام الزوار": يمكن الدخول كزائر فوراً برصيد 500 رسالة (يظهر لك العداد بوضوح)، وعند استنفاده يمكنك ترقية حسابك بالتسجيل الكامل مجاناً.
5. "الشروط العمرية": المنصة مخصصة للبالغين 18+ حفاظاً على أمان وبيئة الحوار.
6. "الاقتصاد والمحفظة": الكوينز تكتسب من المهام اليومية، التحديات، عجلة الحظ، وتستخدم لإرسال هدايا فاخرة (وردة، قهوة عربية، صقر عربي، تاج ملوكي) أو شراء باقات VIP.
7. "نظام المستويات والشعلة": كل رسالة وتفاعل يمنحك نقاط خبرة (XP) لرفع مستواك، وتسجيل الدخول اليومي يحافظ على شعلتك (Streak).
8. "الأمان والخصوصية": يمكنك حظر أو كتم أو الإبلاغ عن أي متجاوز، وقفل الرسائل الخاصة للأصدقاء فقط من الإعدادات.

حدودك الصارمة التي لا تتجاوزها أبداً:
- أنت مرشد ومجيب فقط، ولست مشرفاً ولا تملك صلاحيات إدارة.
- لا تمنح كوينز أو نقاط خبرة أبداً.
- لا تستطيع حظر أو كتم أو طرد أو تعديل أي حساب.
- لا تقرأ المحادثات الخاصة ولا ترسل رسائل نيابة عن أي شخص.
- لا تفصح عن أي أسرار أو معلومات برمجية أو تقنية داخلية.
- تحدث دائماً باللغة العربية الفصحى الودية والموجزة.`;

export async function askAssistant(userMessage: string, userContext?: { username?: string; isGuest?: boolean }): Promise<string> {
  if (genAI && apiKey) {
    try {
      const response = await genAI.models.generateContent({
        model: 'gemini-3.8-flash',
        contents: [
          {
            role: 'user',
            parts: [{ text: `${SYSTEM_PROMPT}\n\nالمستخدم (${userContext?.username || 'ضيف'}): ${userMessage}` }]
          }
        ]
      });

      if (response.text) {
        return response.text.trim();
      }
    } catch (err) {
      console.warn('Gemini API query error, falling back to local guide response:', err);
    }
  }

  // Knowledgeable intelligent local Arabic fallback
  const query = userMessage.toLowerCase();
  if (query.includes('زائر') || query.includes('ضيف') || query.includes('guest')) {
    return 'أهلاً بك! يتيح لك نظام الزائر الدخول السريع برصيد 500 رسالة لتجربة فضفضه. يمكنك متابعة عداد الرسائل المتبقية أعلى الشاشة، وللحفاظ على رصيد لا نهائي وأصدقائك ننصحك بإنشاء حساب دائم مجاناً (18+).';
  }
  if (query.includes('غرف') || query.includes('مجالس') || query.includes('room')) {
    return 'قسم "الغرف والمجالس" مخصص للحوارات الجماعية الممتعة وهو منفصل تماماً عن "المتصلون الآن". يقوم المالك والإدارة بإنشاء مجالس متخصصة ومحمية، حيث يمكنك التحدث والتفاعل مع باقي الأعضاء بالصوت والنص.';
  }
  if (query.includes('كوينز') || query.includes('محفظة') || query.includes('فلوس') || query.includes('coins')) {
    return 'يمكنك كسب الكوينز ونقاط الخبرة (XP) عبر إتمام المهام اليومية، الدخول المتتالي للمحافظة على الشعلة 🔥، تدوير عجلة الحظ، والمشاركة في مسابقات الأمثال. تستخدم الكوينز لإرسال هدايا فاخرة وفتح ميزات VIP.';
  }
  if (query.includes('ذاتي') || query.includes('تدمير') || query.includes('صورة مؤقتة')) {
    return 'تدعم منصة فضفضه ميزة الصور ذاتية التدمير في المحادثات الخاصة! يمكنك اختيار "مشاهدة لمرة واحدة" أو تحديد مؤقت ثوانٍ، وسيقوم النظام فوراً بحذف الصورة وخادمها بمجرد انقضاء المدة لضمان أقصى درجات الخصوصية.';
  }
  if (query.includes('عمر') || query.includes('18') || query.includes('تسجيل')) {
    return 'التسجيل في منصة فضفضه يتطلب أن يكون عمرك 18 عاماً فما فوق استناداً لتاريخ الميلاد المدخل، حرصاً على مجتمع ناضج وآمن لجميع المشتركين.';
  }
  if (query.includes('بلاغ') || query.includes('حظر') || query.includes('مضايقة') || query.includes('أمان')) {
    return 'سلامتك أولويتنا في فضفضه. في الملف الشخصي لأي مستخدم أو داخل المحادثة، تجد خيارات فورية للحظر وكتم الصوت وتقديم بلاغ رسمي للإدارة مع إمكانية إرفاق الدليل للتعامل السريع والصارم.';
  }
  if (query.includes('مالك') || query.includes('hegazy') || query.includes('حجازي')) {
    return 'حساب المالك "Hegazy" هو الحساب الإداري الأعلى لمنصة فضفضه، وهو محمي ومخصص لإدارة شؤون المنصة وتطويرها وضمان جودة التجربة الاجتماعية.';
  }

  return 'أهلاً بك في منصة "فضفضه"! أنا مساعدك الذكي هنا لإرشادك حول كيفية استخدام مميزات المنصة (المتصلون الآن، المجالس الحوارية، الرسائل الخاصة والصور ذاتية التدمير، المهام والشعلة اليومية، ونظام VIP). كيف يمكنني مساعدتك اليوم؟';
}
